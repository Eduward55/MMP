let lang = 'pt';
const listeners = new Set();

export function getLang() {
  return lang;
}

export function localeTag() {
  return lang === 'en' ? 'en-US' : 'pt-BR';
}

export function t(key, vars) {
  const dict = DICT[lang] || DICT.pt;
  let s = dict[key] || DICT.pt[key];
  if (s == null) s = typeof vars === 'string' ? vars : key;
  if (vars && typeof vars === 'object') {
    s = String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? `{${k}}` : String(vars[k])));
  }
  return s;
}

export function formatDay(iso) {
  try {
    return new Date(iso).toLocaleDateString(localeTag(), { day: '2-digit', month: 'short', year: 'numeric' });
  } catch {
    return iso;
  }
}

export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function applyLang(id, persist = true) {
  lang = id === 'en' ? 'en' : 'pt';
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
  if (persist) {
    try {
      localStorage.setItem(KEY, lang);
    } catch {}
    kv.set(KEY, lang).catch(() => {});
  }
  listeners.forEach((fn) => fn(lang));
  window.dispatchEvent(new CustomEvent('mmp-lang', { detail: lang }));
}

export function setLang(id) {
  const next = id === 'en' ? 'en' : 'pt';
  if (next === lang) return lang;
  applyLang(next, true);
  return lang;
}

export async function loadLang() {
  let id = null;
  try {
    id = await kv.get(KEY);
  } catch {}
  if (!id) {
    try {
      id = localStorage.getItem(KEY);
    } catch {}
  }
  applyLang(id === 'en' ? 'en' : 'pt', false);
}

export function createLangToggle() {
  const wrap = el('div', { class: 'lang-toggle', role: 'group', 'aria-label': t('lang.label') });
  const paint = () => {
    wrap.setAttribute('aria-label', t('lang.label'));
    wrap.innerHTML = '';
    [
      ['en', 'English'],
      ['pt', 'Português']
    ].forEach(([id, label]) => {
      wrap.append(
        el(
          'button',
          {
            class: `lang-toggle__btn ${lang === id ? 'is-on' : ''}`,
            type: 'button',
            'aria-pressed': String(lang === id),
            onclick: () => setLang(id)
          },
          label
        )
      );
    });
  };
  paint();
  onLang(() => {
    if (wrap.isConnected) paint();
  });
  return wrap;
}
